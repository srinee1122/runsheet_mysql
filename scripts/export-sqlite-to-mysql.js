// scripts/export-sqlite-to-mysql.js — one-time migration helper.
//
// Reads the old SQLite runsheet.db and writes a MySQL .sql dump that can be uploaded through
// GoDaddy's "Import SQL" (Settings > Hosted Database). GoDaddy drops existing tables before
// running the file, so the dump is fully self-contained: it creates every table (using the
// exact same definitions the app applies on boot, from schema.js), then inserts every row
// with its original id preserved, so runsheet_versions still points at the right runsheets.
//
// Usage:
//   node scripts/export-sqlite-to-mysql.js <path-to-runsheet.db> <output.sql>
//
// Reads only. Never modifies the SQLite file.
'use strict';
const fs = require('fs');
const path = require('path');
const { DatabaseSync } = require('node:sqlite');
const mysql = require('mysql2');
const { SCHEMA, MIGRATIONS } = require(path.join(__dirname, '..', 'schema.js'));

const [,, srcPath, outPath] = process.argv;
if (!srcPath || !outPath) {
  console.error('Usage: node scripts/export-sqlite-to-mysql.js <runsheet.db> <output.sql>');
  process.exit(1);
}

const src = new DatabaseSync(srcPath, { readOnly: true });

// Insert order matters: runsheet_versions references runsheets by FK.
const TABLES = ['products', 'customers', 'settings', 'users', 'runsheets', 'runsheet_versions'];
const CHUNK = 200; // rows per INSERT statement

const out = [];
out.push('-- Generated by scripts/export-sqlite-to-mysql.js');
out.push(`-- Source: ${path.basename(srcPath)}  Exported: ${new Date().toISOString()}`);
out.push('SET NAMES utf8mb4;');
out.push("SET time_zone = '+00:00';");
out.push('SET FOREIGN_KEY_CHECKS = 0;');
out.push('');

// Drop in reverse dependency order (GoDaddy does this too, but a self-contained file is
// also what lets the exact same dump be tested locally first).
for (const t of [...TABLES].reverse()) out.push(`DROP TABLE IF EXISTS \`${t}\`;`);
out.push('DROP TABLE IF EXISTS `_diag`;');
out.push('');

// Tables exactly as the app defines them, then every migration column added — on a fresh
// database none of them exist yet, which is precisely what the app's own ensureColumns
// would do at boot. Emitting them here means the import is complete before the app starts.
for (const ddl of SCHEMA) out.push(ddl + ';');
out.push('');
for (const [table, cols] of Object.entries(MIGRATIONS)) {
  for (const [name, def] of Object.entries(cols)) out.push(`ALTER TABLE \`${table}\` ADD COLUMN \`${name}\` ${def};`);
}
out.push('');

// Columns the MySQL side actually has, per table — read back from the DDL text so an
// unexpected extra column in the SQLite file is skipped rather than breaking the import.
function mysqlColumns(table) {
  const ddl = SCHEMA.find(d => d.includes(`CREATE TABLE IF NOT EXISTS ${table} `));
  const body = ddl.slice(ddl.indexOf('(') + 1, ddl.lastIndexOf(')'));
  const cols = [];
  for (const line of body.split('\n')) {
    const m = line.trim().match(/^`?([a-z_]+)`?\s+(INT|VARCHAR|DOUBLE|TINYINT|DATETIME|LONGTEXT)/i);
    if (m) cols.push(m[1]);
  }
  for (const name of Object.keys(MIGRATIONS[table] || {})) cols.push(name);
  return cols;
}

const summary = {};
for (const table of TABLES) {
  const sqliteCols = new Set(src.prepare(`PRAGMA table_info(${table})`).all().map(r => r.name));
  const cols = mysqlColumns(table).filter(c => sqliteCols.has(c));
  const rows = src.prepare(`SELECT ${cols.map(c => `"${c}"`).join(', ')} FROM ${table} ORDER BY rowid`).all();
  summary[table] = rows.length;
  if (!rows.length) continue;
  const colList = cols.map(c => `\`${c}\``).join(', ');
  for (let i = 0; i < rows.length; i += CHUNK) {
    const chunk = rows.slice(i, i + CHUNK);
    const values = chunk.map(r => '(' + cols.map(c => {
      const v = r[c];
      // SQLite stored empty strings and NULLs; MySQL columns mostly DEFAULT '' — keep NULL as
      // NULL only where the column is nullable, otherwise coerce to '' to satisfy NOT NULL.
      if (v === null || v === undefined) return "''";
      return mysql.escape(v);
    }).join(', ') + ')').join(',\n');
    out.push(`INSERT INTO \`${table}\` (${colList}) VALUES\n${values};`);
  }
  out.push('');
}

out.push('SET FOREIGN_KEY_CHECKS = 1;');
fs.writeFileSync(outPath, out.join('\n') + '\n', 'utf8');

console.log(`Wrote ${outPath} (${(fs.statSync(outPath).size / 1024).toFixed(1)} KB)`);
for (const [t, n] of Object.entries(summary)) console.log(`  ${t.padEnd(18)} ${n} rows`);
